#!/usr/bin/env bash
set -euo pipefail

ADD_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
_add_die() { echo "ERROR: $*" >&2; exit 2; }

_add_add_bind() {
    local p="$1" resolved parent target link
    [[ -n "$p" ]] || return 0
    p="${p/#\~/$HOME}"
    if [[ "$p" != /* ]]; then p="$PWD/$p"; fi
    resolved="$(readlink -m -- "$p" 2>/dev/null || realpath -m -- "$p")"

    if [[ -d "$p" ]]; then
        _ADD_BINDS+=("$p")
        target="$(readlink -f -- "$p" 2>/dev/null || true)"
        [[ -n "$target" && -d "$target" ]] && _ADD_BINDS+=("$target")
    else
        parent="$(dirname "$p")"
        [[ -d "$parent" ]] || mkdir -p "$parent"
        _ADD_BINDS+=("$parent")
        if [[ -e "$p" || -L "$p" ]]; then
            target="$(readlink -f -- "$p" 2>/dev/null || true)"
            if [[ -n "$target" ]]; then
                if [[ -d "$target" ]]; then
                    _ADD_BINDS+=("$target")
                else
                    _ADD_BINDS+=("$(dirname "$target")")
                fi
            fi
        else
            parent="$(dirname "$resolved")"
            [[ -d "$parent" ]] || mkdir -p "$parent"
            _ADD_BINDS+=("$parent")
        fi
    fi
}

_add_add_mapped_path() {
    local value="$1" path="$1"
    if [[ "$value" == *=* ]]; then
        path="${value#*=}"
    elif [[ "$value" == *:* ]]; then
        path="${value#*:}"
    fi
    _add_add_bind "$path"
}

_add_add_bind_tree_symlink_targets() {
    local root="$1" link target
    _add_add_bind "$root"
    # Scan only explicitly designated reference directories, never broad user
    # bind roots such as /data. This avoids expensive whole-filesystem walks.
    while IFS= read -r -d '' link; do
        target="$(readlink -f -- "$link" 2>/dev/null || true)"
        [[ -n "$target" ]] || continue
        if [[ -d "$target" ]]; then
            _add_add_bind "$target"
        else
            _add_add_bind "$(dirname "$target")"
        fi
    done < <(find "$root" -type l -print0 2>/dev/null || true)
}

run_add_tool() {
    local script="$1"; shift
    local sif="${RNA_EDITING_SIF:-}" arg value key
    local -a py_args=() user_binds=() bind_args=() cmd=()
    declare -ga _ADD_BINDS=()

    # Help is generated by the standard-library argparse parser on the host.
    # It must not require an SIF image, Apptainer, or project input files.
    for arg in "$@"; do
        if [[ "$arg" == "-h" || "$arg" == "--help" ]]; then
            command -v python3 >/dev/null 2>&1 || _add_die "python3 is required to display help"
            [[ -f "$script" ]] || _add_die "Python script not found: $script"
            python3 "$script" --help
            return $?
        fi
    done

    while (($#)); do
        arg="$1"
        case "$arg" in
            --sif)
                (($# >= 2)) || _add_die "--sif requires a file"
                sif="$2"; shift 2 ;;
            --bind|-B)
                (($# >= 2)) || _add_die "$arg requires a path"
                user_binds+=("$2"); shift 2 ;;
            --input|--output|--sites|--gtf|--genome|--outdir|--output_dir|--reference_dir|--work_dir)
                (($# >= 2)) || _add_die "$arg requires a value"
                key="$arg"; value="$2"
                case "$key" in
                    --outdir|--output_dir|--work_dir)
                        mkdir -p "$value"
                        _add_add_bind "$value" ;;
                    --output)
                        mkdir -p "$(dirname "$value")"
                        _add_add_mapped_path "$value" ;;
                    --gtf|--genome)
                        _add_add_mapped_path "$value" ;;
                    --reference_dir)
                        [[ -d "$value" ]] || _add_die "Reference directory not found: $value"
                        _add_add_bind_tree_symlink_targets "$value" ;;
                    *) _add_add_bind "$value" ;;
                esac
                py_args+=("$arg" "$value"); shift 2 ;;
            *) py_args+=("$arg"); shift ;;
        esac
    done

    [[ -n "$sif" ]] || _add_die "Set RNA_EDITING_SIF or pass --sif /path/to/rna_editing.sif"
    [[ -r "$sif" ]] || _add_die "SIF is not readable: $sif"
    command -v apptainer >/dev/null 2>&1 || _add_die "apptainer is not in PATH"
    [[ -f "$script" ]] || _add_die "Python script not found: $script"

    _add_add_bind "$script"
    _add_add_bind "$ADD_DIR"
    _add_add_bind "$PWD"
    for value in "${user_binds[@]}"; do _add_add_bind "$value"; done

    local -A seen=()
    for value in "${_ADD_BINDS[@]}"; do
        [[ -n "$value" && -d "$value" ]] || continue
        value="$(readlink -m -- "$value")"
        [[ -n "${seen[$value]+x}" ]] && continue
        seen[$value]=1
        bind_args+=(--bind "$value:$value")
    done

    cmd=(apptainer exec "${bind_args[@]}" "$sif" python3 "$script" "${py_args[@]}")
    exec "${cmd[@]}"
}
